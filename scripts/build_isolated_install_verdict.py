"""Publish the isolated-install verdict into the tracked tree (audit items F06 / A08).

``scripts/verify_isolated_install.py`` writes its report under ``.project-local/build/``,
which ``.gitignore`` line 2 excludes. That makes the strongest single claim of this
round -- "the project installs offline into an isolated directory, imports from that
install, and the legacy regression suite runs there: 170 passed, overall PASS,
blocked = []" -- invisible from a clone. It is the same class of defect already fixed
here for ``config/environment-baseline.json`` and ``docs/AUDIT-STATE.json``.

This script does not restate the verdict by hand. It re-reads the report the producer
wrote, binds the tracked record to that report's bytes with a SHA-256, and collapses the
machine-specific prefix of every path (``<REPO>``, ``<HOME>``) so no user home directory
enters Git. With no report on the machine it refuses instead of emitting an empty record,
and points at the two commands that create one.
"""
from __future__ import annotations

import argparse
import datetime
import glob
import hashlib
import json
import os
import re
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from published_stamp import keeping_the_recorded_stamp  # noqa: E402

TARGET_ROOT = Path(__file__).resolve().parents[1]
OUT = TARGET_ROOT / "config" / "isolated-install-verdict.json"
BUILD_GLOB = str(TARGET_ROOT / ".project-local" / "build" / "*" / "verify-report.json")
_ROOT = str(TARGET_ROOT).replace("\\", "/")
_HOME = str(Path.home()).replace("\\", "/")

# the numbers a reviewer needs -- counts, digests, verdicts, the argv that produced them
_KEEP_FIELD = re.compile(r"(count|sha|digest|files|passed|exit|wheel|top_level|missing|"
                         r"expected|version|origin|detail|command|^id$|summary|state|result)",
                         re.IGNORECASE)


def collapse(value):
    """Repo/home-relative paths only; nothing machine-specific survives.

    Both spellings are replaced and the replacement is a substring search, not a prefix
    test: the install report records whole command lines, so ``C:/Users/<name>/Temp/...``
    appears *inside* an argv string. A prefix-only collapse let six of those through while
    a guard that only looked for the backslash spelling stayed green.
    """
    if isinstance(value, str):
        text = value.replace("\\", "/")
        for prefix, token in ((_HOME, "<HOME>"), (_ROOT, "<REPO>"), (str(Path.home()), "<HOME>")):
            if prefix and prefix in text:
                text = text.replace(prefix, token)
        return text
    if isinstance(value, list):
        return [collapse(item) for item in value]
    if isinstance(value, dict):
        return {key: collapse(item) for key, item in value.items()}
    return value


def build(report_path: Path) -> dict:
    blob = report_path.read_bytes()
    document = json.loads(blob.decode("utf-8-sig"))
    checks = []
    for check in document.get("checks") or []:
        entry = {"id": check.get("id"), "verdict": check.get("verdict")}
        for key, value in check.items():
            if key not in ("id", "verdict") and _KEEP_FIELD.search(key):
                entry[key] = collapse(value)
        checks.append(entry)
    return dict(
        schema="ai-work-lab/isolated-install-verdict/v1",
        purpose=("tracked receipt for audit items F06/A08: an offline install into an isolated "
                 "directory, imported from that install, with the legacy regression suite run "
                 "there. Generated by scripts/build_isolated_install_verdict.py from the "
                 "producer's own report -- not transcribed by hand."),
        generated_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),
        observed_from=dict(report=str(report_path.relative_to(TARGET_ROOT)).replace("\\", "/"),
                           sha256=hashlib.sha256(blob).hexdigest(), bytes=len(blob)),
        producer_commands=collapse([sys.executable + " -B -X utf8 scripts/build_offline_install.py",
                                    sys.executable + " -B -X utf8 scripts/verify_isolated_install.py"]),
        overall=document.get("overall"),
        failed_required=collapse(document.get("failed_required") or []),
        blocked=collapse(document.get("blocked") or []),
        checks=checks,
        check_ids=[check["id"] for check in checks],
        interpreter=collapse(document.get("interpreter")),
        os=collapse(document.get("os")),
        wheel_sha256=collapse(document.get("wheel_sha256")),
        run_window=dict(started=document.get("generated_at"),
                        finished=document.get("finished_at")),
        note=("path values are collapsed to <REPO>/<HOME> prefixes; the install tree itself "
              "lives under .project-local and is not in Git. Where the local report still "
              "exists, tests/unified/test_v25_audit_item_closure.py re-reads it and fails if "
              "this record no longer matches its bytes. Where it does not, run "
              "producer_commands and regenerate -- do not edit this file to match prose."),
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--report", help="a specific verify-report.json to publish")
    parser.add_argument("--check", action="store_true",
                        help="compare the tracked record with the local report; write nothing")
    args = parser.parse_args((argv or sys.argv)[1:])

    candidates = sorted(glob.glob(BUILD_GLOB), key=os.path.getmtime)
    if args.report:
        candidates = [args.report]
    if not candidates:
        print(json.dumps(dict(
            error="NO_ISOLATED_INSTALL_REPORT",
            hint="run scripts/build_offline_install.py then scripts/verify_isolated_install.py; "
                 "this record can only be published where the install actually ran"),
            ensure_ascii=True), file=sys.stderr)
        return 2
    report = Path(candidates[-1])
    document = build(report)
    document = keeping_the_recorded_stamp(OUT, document)
    rendered = json.dumps(document, ensure_ascii=False, indent=2) + "\n"
    facts = dict(report=str(report.relative_to(TARGET_ROOT)).replace("\\", "/"),
                 verdict=document["overall"], checks=len(document["checks"]),
                 blocked=len(document["blocked"]),
                 failed_required=len(document["failed_required"]))
    if args.check:
        # the record stamps its own clock, so a comparison that kept generated_at would
        # report drift on every run of any date. Everything else is compared in full.
        def without_stamp(text):
            if text is None:
                return None
            parsed = json.loads(text)
            parsed.pop("generated_at", None)
            return json.dumps(parsed, ensure_ascii=False, sort_keys=True)
        facts["drift"] = without_stamp(OUT.read_text(encoding="utf-8-sig")
                                       if OUT.is_file() else None) != without_stamp(rendered)
        print(json.dumps(facts, ensure_ascii=True))
        return 1 if facts["drift"] else 0
    OUT.write_text(rendered, encoding="utf-8", newline="\n")
    facts["written"] = str(OUT.relative_to(TARGET_ROOT)).replace("\\", "/")
    print(json.dumps(facts, ensure_ascii=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
